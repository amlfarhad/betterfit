#!/usr/bin/env python3
"""Configure Form from a user-supplied iOS OAuth download, without copying secrets."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import plistlib
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PRIVATE_KEYS = {"client_secret", "access_token", "refresh_token", "id_token", "private_key"}
CLIENT_ID = re.compile(r"[A-Za-z0-9-]+\.apps\.googleusercontent\.com\Z")
BUNDLE_ID = re.compile(r"[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+\Z")


def reject_private_material(value: object) -> None:
    if isinstance(value, dict):
        if any(str(key).lower() in PRIVATE_KEYS for key in value):
            raise ValueError("The file contains a client secret or token. Use the iOS OAuth client download, never Desktop credentials or tokens.")
        for child in value.values():
            reject_private_material(child)
    elif isinstance(value, list):
        for child in value:
            reject_private_material(child)


def read_ios_configuration(path: Path, expected_bundle_id: str) -> tuple[str, str]:
    if path.stat().st_size > 1_048_576:
        raise ValueError("OAuth configuration is unexpectedly large.")
    raw = path.read_bytes()
    try:
        data = plistlib.loads(raw) if path.suffix.lower() == ".plist" else json.loads(raw)
    except (ValueError, plistlib.InvalidFileException) as error:
        raise ValueError("Choose a valid iOS OAuth JSON or plist download.") from error
    if not isinstance(data, dict):
        raise ValueError("The iOS OAuth download must contain an object.")
    reject_private_material(data)
    # iOS plist keys are also accepted in JSON-converted plists. An installed
    # JSON needs explicit iOS bundle identity: the shared Desktop envelope is
    # insufficient evidence of client type and must never be silently accepted.
    entry = data.get("installed", data.get("ios", data))
    if not isinstance(entry, dict):
        raise ValueError("The iOS OAuth entry must contain an object.")
    ios_info = entry.get("ios_info", {})
    if not isinstance(ios_info, dict):
        raise ValueError("The iOS bundle metadata is malformed.")
    bundle = entry.get("BUNDLE_ID") or entry.get("ios_bundle_id") or ios_info.get("bundle_id")
    if not bundle:
        raise ValueError("Missing iOS bundle identity. Desktop/untyped JSON is not accepted; download the iOS plist or iOS JSON from the iOS client page.")
    if bundle != expected_bundle_id:
        raise ValueError("The OAuth iOS bundle does not match --bundle-id. Configure both for the same app.")
    client = entry.get("CLIENT_ID", entry.get("client_id"))
    if not isinstance(client, str) or not CLIENT_ID.fullmatch(client):
        raise ValueError("The iOS client ID has an invalid format.")
    scheme = ".".join(reversed(client.split(".")))
    supplied_scheme = entry.get("REVERSED_CLIENT_ID", entry.get("reversed_client_id"))
    if supplied_scheme is not None and supplied_scheme != scheme:
        raise ValueError("The reversed client ID does not match the client ID.")
    return client, scheme


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("oauth_file", type=Path, help="Downloaded iOS OAuth JSON or plist (not a Desktop client)")
    parser.add_argument("--bundle-id", default="com.amal.form", help="Must match the registered iOS OAuth client")
    parser.add_argument("--app-group", default="group.com.amal.form", help="App Group registered for both app and widget")
    parser.add_argument("--team-id", help="Optional ten-character Apple Developer Team ID")
    args = parser.parse_args()
    try:
        if not BUNDLE_ID.fullmatch(args.bundle_id):
            raise ValueError("The bundle ID must be a reverse-DNS identifier.")
        if not BUNDLE_ID.fullmatch(args.app_group) or not args.app_group.startswith("group."):
            raise ValueError("The App Group must be a reverse-DNS identifier starting with group.")
        if args.team_id and not re.fullmatch(r"[A-Z0-9]{10}", args.team_id):
            raise ValueError("The Apple Team ID must contain ten uppercase letters or digits.")
        client, scheme = read_ios_configuration(args.oauth_file.expanduser(), args.bundle_id)
        lines = [
            "// Local configuration generated by scripts/configure_ios.py. Do not commit.",
            f"FORM_GOOGLE_CLIENT_ID = {client}",
            f"FORM_GOOGLE_REDIRECT_SCHEME = {scheme}",
            f"FORM_BUNDLE_ID = {args.bundle_id}",
            f"FORM_WIDGET_BUNDLE_ID = {args.bundle_id}.widgets",
            f"FORM_APP_GROUP = {args.app_group}",
        ]
        if args.team_id:
            lines.append(f"DEVELOPMENT_TEAM = {args.team_id}")
        output = ROOT / "iOS/Configuration/Local.xcconfig"
        output.parent.mkdir(parents=True, exist_ok=True)
        fd, temporary = tempfile.mkstemp(dir=output.parent, prefix=".Local-", suffix=".xcconfig")
        try:
            with os.fdopen(fd, "w") as handle:
                handle.write("\n".join(lines) + "\n")
            os.chmod(temporary, 0o600)
            os.replace(temporary, output)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
        print("Configured iOS/Configuration/Local.xcconfig with public iOS identifiers only.")
        print("Open iOS/Form.xcodeproj, select the Form scheme, and choose your signing team for both targets.")
        return 0
    except (OSError, ValueError) as error:
        print(f"Configuration not written: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
